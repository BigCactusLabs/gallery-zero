#!/usr/bin/env python3
"""Gallery Zero palettes written out for terminals other than macOS Terminal.app.

Each port is a pure function of a theme's spec colors, so every port file can be
regenerated and compared: `profiles.py sync-ports` writes them under
terminals/<app>/ and `profiles.py verify` checks them. Ports carry colors only.
The glass, window size and title of a Terminal.app profile stay in Terminal.app.

Terminal.app leaves selected text in its own color, and so does every port whose
format can say so: Ghostty, kitty, WezTerm, Alacritty and iTerm2's Dynamic
Profiles. An .itermcolors preset holds colors only, so its selected-text color is
the foreground, and Warp's themes have no selection color at all.
"""

from __future__ import annotations

import json
import plistlib
import uuid
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Mapping, Sequence

SITE_URL = "https://bigcactuslabs.github.io/gallery-zero/"
PORTS_DIR = "terminals"  # terminals/<app>/<theme file>, generated by profiles.py sync-ports
AUTHOR = "Gallery Zero"
LICENSE = "CC BY 4.0"

ANSI = ("black", "red", "green", "yellow", "blue", "magenta", "cyan", "white")
SLOTS = ANSI + tuple(f"bright_{name}" for name in ANSI)

# Fixed so that a work keeps its iTerm2 profile GUID across installs and updates.
GUID_NAMESPACE = uuid.UUID("6f0e3c2a-5d1b-4c8e-9a47-2b8d1f6e0c93")


@dataclass(frozen=True)
class Work:
    """One theme, as the ports see it."""

    name: str  # "Rothko — Four Darks in Red", the Terminal.app profile name
    anchor: str  # "rothko-four-darks-in-red", the work's id on the gallery site
    title: str  # "Four Darks in Red — Rothko, 1958", the Terminal.app window title
    colors: Mapping[str, str]

    @property
    def artist(self) -> str:
        return self.name.split(" — ", 1)[0]

    @property
    def url(self) -> str:
        return f"{SITE_URL}#{self.anchor}"


def _q(text: str) -> str:
    """A double-quoted string that TOML and YAML both read."""
    return json.dumps(text, ensure_ascii=False)


def _header(work: Work) -> list[str]:
    return [f"# {work.name}", f"# {AUTHOR} · {LICENSE} · {work.url}"]


def _luminance(hex_color: str) -> float:
    def linear(channel: float) -> float:
        return channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4

    r, g, b = (linear(int(hex_color[i : i + 2], 16) / 255) for i in (1, 3, 5))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def is_light(hex_color: str) -> bool:
    """True when dark text reads better on this color than light text does."""
    lum = _luminance(hex_color)
    return (lum + 0.05) / 0.05 > 1.05 / (lum + 0.05)


def ghostty(work: Work) -> str:
    c = work.colors
    lines = _header(work)
    lines += [f"palette = {i}={c[slot]}" for i, slot in enumerate(SLOTS)]
    lines += [
        f"background = {c['background']}",
        f"foreground = {c['foreground']}",
        f"cursor-color = {c['cursor']}",
        f"cursor-text = {c['cursor_text']}",
        f"selection-background = {c['selection']}",
        "selection-foreground = cell-foreground",
    ]
    return "\n".join(lines) + "\n"


def kitty(work: Work) -> str:
    c = work.colors
    lines = [
        "# vim:ft=kitty",
        f"## name: {work.name}",
        f"## author: {AUTHOR}",
        f"## license: {LICENSE}",
        f"## upstream: {work.url}",
        f"## blurb: {work.title}",
        "",
        f"foreground {c['foreground']}",
        f"background {c['background']}",
        f"cursor {c['cursor']}",
        f"cursor_text_color {c['cursor_text']}",
        "selection_foreground none",
        f"selection_background {c['selection']}",
    ]
    lines += [f"color{i} {c[slot]}" for i, slot in enumerate(SLOTS)]
    return "\n".join(lines) + "\n"


def wezterm(work: Work) -> str:
    c = work.colors

    def array(slots: Sequence[str]) -> str:
        return "[" + ", ".join(_q(c[slot]) for slot in slots) + "]"

    lines = _header(work) + [
        "",
        "[colors]",
        f"foreground = {_q(c['foreground'])}",
        f"background = {_q(c['background'])}",
        f"cursor_bg = {_q(c['cursor'])}",
        f"cursor_border = {_q(c['cursor'])}",
        f"cursor_fg = {_q(c['cursor_text'])}",
        f"selection_bg = {_q(c['selection'])}",
        'selection_fg = "none"',  # transparent, so each cell keeps its own color
        f"ansi = {array(SLOTS[:8])}",
        f"brights = {array(SLOTS[8:])}",
        "",
        "[metadata]",
        f"name = {_q(work.name)}",
        f"author = {_q(AUTHOR)}",
        f"origin_url = {_q(work.url)}",
    ]
    return "\n".join(lines) + "\n"


def alacritty(work: Work) -> str:
    c = work.colors
    tables = {
        "colors.primary": [
            ("background", c["background"]),
            ("foreground", c["foreground"]),
            ("bright_foreground", c["bold"]),
        ],
        "colors.cursor": [("text", c["cursor_text"]), ("cursor", c["cursor"])],
        "colors.selection": [("text", "CellForeground"), ("background", c["selection"])],
        "colors.normal": [(name, c[name]) for name in ANSI],
        "colors.bright": [(name, c[f"bright_{name}"]) for name in ANSI],
    }
    lines = _header(work)
    for table, pairs in tables.items():
        lines += ["", f"[{table}]"] + [f"{key} = {_q(value)}" for key, value in pairs]
    return "\n".join(lines) + "\n"


def warp(work: Work) -> str:
    c = work.colors
    lines = _header(work) + [
        f"name: {_q(work.name)}",
        f"accent: {_q(c['cursor'])}",
        f"cursor: {_q(c['cursor'])}",
        f"background: {_q(c['background'])}",
        f"foreground: {_q(c['foreground'])}",
        f"details: {'lighter' if is_light(c['background']) else 'darker'}",
        "terminal_colors:",
        "  normal:",
    ]
    lines += [f"    {name}: {_q(c[name])}" for name in ANSI]
    lines += ["  bright:"] + [f"    {name}: {_q(c[f'bright_{name}'])}" for name in ANSI]
    return "\n".join(lines) + "\n"


ITERM_KEYS = {f"Ansi {i} Color": slot for i, slot in enumerate(SLOTS)} | {
    "Background Color": "background",
    "Foreground Color": "foreground",
    "Bold Color": "bold",
    "Cursor Color": "cursor",
    "Cursor Text Color": "cursor_text",
    "Selection Color": "selection",
    "Selected Text Color": "foreground",
}


def _iterm_color(hex_color: str) -> dict[str, object]:
    r, g, b = (round(int(hex_color[i : i + 2], 16) / 255, 6) for i in (1, 3, 5))
    return {
        "Alpha Component": 1.0,
        "Blue Component": b,
        "Color Space": "sRGB",
        "Green Component": g,
        "Red Component": r,
    }


def iterm_colors(work: Work) -> dict[str, dict[str, object]]:
    return {key: _iterm_color(work.colors[slot]) for key, slot in ITERM_KEYS.items()}


def iterm2(work: Work) -> str:
    xml = plistlib.dumps(iterm_colors(work), fmt=plistlib.FMT_XML, sort_keys=True).decode()
    note = f"<!-- {work.name} · {AUTHOR} · {LICENSE} · {work.url} -->\n"
    return xml.replace("<plist", note + "<plist", 1)


def iterm_guid(work: Work) -> str:
    return str(uuid.uuid5(GUID_NAMESPACE, work.name)).upper()


# A Dynamic Profile inherits every key it leaves out from the user's default profile.
# iTerm2's own default keeps separate light and dark colors, which would hide these
# unsuffixed colors, so each profile turns that off. Selected text keeps its color.
ITERM_PROFILE_FLAGS = {
    "Use Separate Colors for Light and Dark Mode": False,
    "Use Selected Text Color": False,
}


def iterm_dynamic_profiles(works: Sequence[Work], keep: Sequence[Mapping[str, object]] = ()) -> str:
    """An iTerm2 Dynamic Profiles file: one sparse profile per work.

    Anything a profile leaves out (font, window size, keys) comes from the
    user's default profile, as the Terminal.app installer keeps the user's font.
    `keep` carries installed profiles of retired works through unchanged.
    """
    profiles = [
        {"Name": w.name, "Guid": iterm_guid(w), "Tags": [AUTHOR, w.artist], **ITERM_PROFILE_FLAGS, **iterm_colors(w)}
        for w in works
    ]
    return json.dumps({"Profiles": profiles + list(keep)}, ensure_ascii=False, indent=2, sort_keys=False) + "\n"


def is_port(head: str) -> bool:
    """Whether a theme file's opening text is a Gallery Zero header. --prune deletes no other file."""
    return AUTHOR in head and SITE_URL in head


@dataclass(frozen=True)
class Port:
    app: str  # the folder under terminals/ and the installer's --terminal value
    label: str
    extension: str  # "" for Ghostty, whose theme names are file names
    render: Callable[[Work], str]
    unsafe: str = ""  # characters dropped from the work's name to make the theme name

    def theme_name(self, work: Work) -> str:
        return "".join(ch for ch in work.name if ch not in self.unsafe)

    def filename(self, work: Work) -> str:
        return f"{self.theme_name(work)}{self.extension}"


PORTS = (
    # Ghostty reads a comma, colon or equals sign in `theme =` as a light/dark pair,
    # so "Tanaka — Thanks, Sam" is the theme "Tanaka — Thanks Sam".
    Port("ghostty", "Ghostty", "", ghostty, unsafe=",:="),
    Port("iterm2", "iTerm2", ".itermcolors", iterm2),
    Port("kitty", "kitty", ".conf", kitty),
    Port("wezterm", "WezTerm", ".toml", wezterm),
    Port("alacritty", "Alacritty", ".toml", alacritty),
    Port("warp", "Warp", ".yaml", warp),
)
BY_APP = {port.app: port for port in PORTS}


def theme_dir(app: str, env: Mapping[str, str], platform: str) -> Path:
    """Where each terminal looks for themes (iTerm2: its Dynamic Profiles folder)."""
    home = Path(env.get("HOME") or Path.home())
    config = Path(env["XDG_CONFIG_HOME"]) if env.get("XDG_CONFIG_HOME") else home / ".config"
    if app == "ghostty":
        return config / "ghostty" / "themes"
    if app == "kitty":
        kitty_home = env.get("KITTY_CONFIG_DIRECTORY")
        return (Path(kitty_home) if kitty_home else config / "kitty") / "themes"
    if app == "wezterm":
        return config / "wezterm" / "colors"
    if app == "alacritty":
        return config / "alacritty" / "themes"
    if app == "warp":
        if platform == "darwin":
            return home / ".warp" / "themes"
        data = Path(env["XDG_DATA_HOME"]) if env.get("XDG_DATA_HOME") else home / ".local" / "share"
        return data / "warp-terminal" / "themes"
    if app == "iterm2":
        return home / "Library" / "Application Support" / "iTerm2" / "DynamicProfiles"
    raise ValueError(f"unknown terminal: {app}")


def how_to_use(app: str, example: Work, directory: str) -> str:
    """How to switch to a theme the installer just wrote."""
    if app == "ghostty":
        return f"Set it in your Ghostty config: theme = {BY_APP[app].theme_name(example)}  (preview: ghostty +list-themes)"
    if app == "kitty":
        return "Pick one with: kitten themes  (Gallery Zero themes are listed under User)"
    if app == "wezterm":
        return f'Set it in wezterm.lua: config.color_scheme = "{example.name}"'
    if app == "alacritty":
        path = f"{directory}/{BY_APP[app].filename(example)}"
        return f"Add it to alacritty.toml:\n\n[general]\nimport = [{_q(path)}]"
    if app == "warp":
        return "Choose one in Warp: Settings > Appearance > Themes"
    if app == "iterm2":
        return "Choose one in iTerm2: Settings > Profiles (tagged Gallery Zero)"
    raise ValueError(f"unknown terminal: {app}")
